#include "../../includes/libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*last_lst;

	if (!new)
		return ;
	if (!*lst)
	{
		*lst = new;
		return ;
	}
	last_lst = *lst;
	while (last_lst && last_lst->next)
		last_lst = last_lst->next;
	last_lst->next = new;
}
